import type { ApiResponse } from '@ethica/contracts';
import { t } from '../helpers/translate.helper.js';

// No access token/Zustand (AD-014) — the only credential is the httpOnly cookie
// the browser itself attaches through credentials:'include'. Simplified port
// of ../DentalEase/DentalEase/src/lib/api/client.api.ts, without the
// `authorization` header branch (there is no access token here).
const BASE_URL = (import.meta.env.VITE_API_URL as string | undefined) ?? '';

// Absolute URL of a resource the browser loads by itself (e.g. the user photo `<img src>`,
// ACC-06); the session cookie goes along as in any request.
export const apiUrl = (path: string): string => `${BASE_URL}${path}`;

type Method = 'GET' | 'POST' | 'PATCH' | 'PUT' | 'DELETE';

const CONNECTION_ERROR_MESSAGE = t('connection_error');

// The API `message` is always a translation KEY (`ApiMessageKey`,
// @ethica/contracts response/messages.ts), never ready-made text — translated here,
// at the single entry point of the responses, so toast, form error
// and query `Error` get the pt-BR text without any screen calling `t()` again
// on `res.message`. `''` (success without a message) passes untouched.
const translateMessage = <T>(body: ApiResponse<T>): ApiResponse<T> =>
  body.message ? { ...body, message: t(body.message) } : body;

// Never throws: a network failure becomes an ApiResponse with success:false, so
// every screen reads `message` without try/catch (FND-10/AC4).
export const request = async <T>(path: string, method: Method, body?: unknown): Promise<ApiResponse<T>> => {
  try {
    const res = await fetch(`${BASE_URL}${path}`, {
      method,
      credentials: 'include',
      headers: body !== undefined ? { 'Content-Type': 'application/json' } : undefined,
      body: body !== undefined ? JSON.stringify(body) : undefined,
    });
    return translateMessage((await res.json()) as ApiResponse<T>);
  } catch {
    return { success: false, message: CONNECTION_ERROR_MESSAGE };
  }
};

// File as the request body (AD-118): import PDF and CSV (POST) and inspection media
// (PUT, idempotent by id, AD-129). The type goes explicitly because the browser does not always
// know it (CSV arrives as `application/vnd.ms-excel` on Windows).
export const sendFile = async <T>(
  path: string,
  file: Blob,
  type: string,
  method: 'POST' | 'PUT' = 'POST',
): Promise<ApiResponse<T>> => {
  try {
    const res = await fetch(`${BASE_URL}${path}`, {
      method,
      credentials: 'include',
      headers: { 'Content-Type': type },
      body: file,
    });
    return translateMessage((await res.json()) as ApiResponse<T>);
  } catch {
    return { success: false, message: CONNECTION_ERROR_MESSAGE };
  }
};

// File generated by the API (PDF and ZIP, AD-119/AD-122). An error arrives in the usual format (JSON
// with the message key); success is the file itself, with the Content-Disposition name.
export type FileResponse = { success: true; blob: Blob; filename: string } | { success: false; message: string };

export const getFile = async (path: string): Promise<FileResponse> => {
  try {
    const res = await fetch(`${BASE_URL}${path}`, { method: 'GET', credentials: 'include' });
    if (!res.ok) {
      const body = translateMessage((await res.json()) as ApiResponse<never>);
      return { success: false, message: body.message || t('action_error') };
    }
    const filename = res.headers.get('content-disposition')?.match(/filename="([^"]+)"/)?.[1] ?? 'document';
    return { success: true, blob: await res.blob(), filename };
  } catch {
    return { success: false, message: CONNECTION_ERROR_MESSAGE };
  }
};

export const get = <T>(path: string): Promise<ApiResponse<T>> => request<T>(path, 'GET');
export const post = <T>(path: string, body?: unknown): Promise<ApiResponse<T>> => request<T>(path, 'POST', body);
export const patch = <T>(path: string, body?: unknown): Promise<ApiResponse<T>> => request<T>(path, 'PATCH', body);
// T36 (scheduling): PUT /scheduling-settings (schedulingSettings.router.ts) is
// the first endpoint of this app to use PUT — the other resources use
// PATCH (partial edit) because they have an id (`/professionals/:id`); scheduling
// settings is a single document per tenant, without an id, so the back-end uses PUT
// (replacing the single resource), not PATCH.
export const put = <T>(path: string, body?: unknown): Promise<ApiResponse<T>> => request<T>(path, 'PUT', body);
// T37 (scheduling): DELETE /appointments/blocks/:id (appointment.router.ts) is
// the first endpoint of this app to use DELETE — no body, same pattern as
// `get`. `delete` is a reserved word, it cannot name a binding
// (`export const delete = ...`), hence `del`.
export const del = <T>(path: string): Promise<ApiResponse<T>> => request<T>(path, 'DELETE');

// T42 (scheduling): the public confirmation page (`_public/appointment`)
// needs to tell 404 (invalid link) from 410 (expired) — the only case in the
// app that depends on the HTTP STATUS itself, not only on the `{success,message}` body
// (errorHandler.middleware.ts always returns the same body format for
// any 4xx/5xx status). Its own function, not a change to `request`/
// `get`: changing what `get` returns would break the existing tests that do a
// strict `toEqual` on the `ApiResponse` shape (client.api.unit.test.ts).
export type ApiResponseWithStatus<T> = ApiResponse<T> & { status: number };

export const getWithStatus = async <T>(path: string): Promise<ApiResponseWithStatus<T>> => {
  try {
    const res = await fetch(`${BASE_URL}${path}`, { method: 'GET', credentials: 'include' });
    const body = translateMessage((await res.json()) as ApiResponse<T>);
    return { ...body, status: res.status };
  } catch {
    return { success: false, message: CONNECTION_ERROR_MESSAGE, status: 0 };
  }
};
