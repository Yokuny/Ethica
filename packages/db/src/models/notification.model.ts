import {
  type CaseProposal,
  type CourtMovement,
  NOTICE_TOPICS,
  NOTIFICATION_KINDS,
  NOTIFICATION_MODULES,
  NOTIFICATION_SEVERITIES,
  NOTIFICATION_SOURCES,
  NOTIFICATION_STATUS,
  type NoticeTopic,
  type NotificationKind,
  type NotificationModule,
  type NotificationSeverity,
  type NotificationSource,
  type NotificationStatus,
} from '@ethica/contracts';
import mongoose, { Schema } from 'mongoose';

// One schema for the four kinds (AD-263): the fields of each kind are optional here and the shape per
// kind is the Zod union of `@ethica/contracts`. The fields enter with the phase that uses them.
export interface NotificationDocument {
  _id: mongoose.Types.ObjectId;
  Tenant: mongoose.Types.ObjectId;
  kind: NotificationKind;
  module: NotificationModule;
  source: NotificationSource;
  // A notice has no status (read per person).
  status?: NotificationStatus;
  Case?: mongoose.Types.ObjectId;
  title?: string;
  // Calendar dates `YYYY-MM-DD` in the display time zone (AD-103): a deadline is a day, not an instant.
  dueDate?: string;
  filedDate?: string;
  notes?: string;
  // Notice (Fase 2): a translation key and its parameters, never a ready sentence.
  topic?: NoticeTopic;
  params?: Record<string, string | number>;
  severity?: NotificationSeverity;
  Transaction?: mongoose.Types.ObjectId;
  // Generated by the system: the same fact never becomes two notifications (e.g. `finance_due:<id>:<bucket>`).
  dedupeKey?: string;
  // A notice leaves the database by itself (TTL).
  expireAt?: Date;
  // Suggestion (Fase 5, AD-268): what would change, the court movement that justifies it and the rule.
  proposal?: CaseProposal;
  evidence?: { court: string; movement: CourtMovement };
  ruleKey?: string;
  ruleVersion?: number;
  decidedBy?: mongoose.Types.ObjectId;
  decidedAt?: Date;
  rejectReason?: string;
  readBy: mongoose.Types.ObjectId[];
  createdAt: Date;
  updatedAt: Date;
}

const DAY = /^\d{4}-\d{2}-\d{2}$/;
const isDated = (kind: NotificationKind): boolean => kind === 'deadline' || kind === 'alert';

const notificationSchema = new Schema<NotificationDocument>(
  {
    Tenant: { type: Schema.Types.ObjectId, ref: 'Tenant', required: true },
    kind: { type: String, enum: NOTIFICATION_KINDS, required: true },
    module: { type: String, enum: NOTIFICATION_MODULES, required: true },
    source: { type: String, enum: NOTIFICATION_SOURCES, required: true },
    status: { type: String, enum: NOTIFICATION_STATUS },
    Case: { type: Schema.Types.ObjectId, ref: 'Case' },
    title: { type: String, trim: true },
    dueDate: { type: String, match: DAY },
    filedDate: { type: String, match: DAY },
    notes: { type: String },
    topic: { type: String, enum: NOTICE_TOPICS },
    params: { type: Schema.Types.Mixed },
    severity: { type: String, enum: NOTIFICATION_SEVERITIES },
    Transaction: { type: Schema.Types.ObjectId, ref: 'Transaction' },
    dedupeKey: { type: String },
    expireAt: { type: Date },
    proposal: { type: Schema.Types.Mixed },
    evidence: { type: Schema.Types.Mixed },
    ruleKey: { type: String },
    ruleVersion: { type: Number },
    decidedBy: { type: Schema.Types.ObjectId, ref: 'User' },
    decidedAt: { type: Date },
    rejectReason: { type: String, trim: true },
    readBy: { type: [Schema.Types.ObjectId], ref: 'User', default: [] },
  },
  { timestamps: true },
);

notificationSchema.pre('validate', function () {
  if (isDated(this.kind)) {
    for (const field of ['Case', 'title', 'dueDate', 'status'] as const) {
      if (!this[field]) this.invalidate(field, `${this.kind} precisa de ${field}`);
    }
  }
  if (this.kind === 'notice' && !this.topic) this.invalidate('topic', 'aviso precisa do assunto');
  if (this.kind === 'suggestion' && (!this.Case || !this.proposal || !this.status)) {
    this.invalidate('proposal', 'sugestão precisa do serviço, da proposta e da situação');
  }
  if (this.status === 'filed' && !this.filedDate) {
    this.invalidate('filedDate', 'prazo protocolado precisa da data de protocolo');
  }
});

// Central and counters; case detail; the reminder scan across tenants (worker, AD-267).
notificationSchema.index({ Tenant: 1, kind: 1, status: 1, dueDate: 1 });
notificationSchema.index({ Tenant: 1, Case: 1, kind: 1, dueDate: 1 });
notificationSchema.index({ status: 1, dueDate: 1 });
notificationSchema.index(
  { Tenant: 1, dedupeKey: 1 },
  { unique: true, partialFilterExpression: { dedupeKey: { $type: 'string' } } },
);
notificationSchema.index({ expireAt: 1 }, { expireAfterSeconds: 0 });

export const Notification = mongoose.model<NotificationDocument>('Notification', notificationSchema);
